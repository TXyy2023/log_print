// Real embedded Rust server; UI, files and download bytes are verified together.
import { chromium, expect } from '../../../project/plugins/outputs/output-webui/frontend/node_modules/@playwright/test/index.mjs';
import { appendFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
const [url, state, binary, artifact, emptyUrl, emptyState, source] = process.argv.slice(2);
await mkdir(artifact, { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true, permissions: ['clipboard-read', 'clipboard-write'] });
await context.tracing.start({ screenshots: true, snapshots: true });
const page = await context.newPage();
const errors = [], checks = [];
page.on('pageerror', error => errors.push(String(error)));
const screenshot = name => page.screenshot({ path: path.join(artifact, name), fullPage: true });
const api = async (method, args = {}) => {
  const response = await context.request.post(`${url}/api/control`, { headers: { Origin: url }, data: { method, args } });
  expect(response.ok()).toBeTruthy(); return response.json();
};
const read = async () => (await context.request.get(`${url}/api/state`)).json();
const text = page.getByRole('textbox', { name: '关键词', exact: true });
const saveFrom = async name => {
  await page.getByRole('button', { name: '保存日志', exact: true }).click();
  await page.getByRole('button', { name: new RegExp('^' + name) }).click();
  await expect(page.getByRole('dialog', { name: /保存记录/ })).toBeVisible();
  await expect(page.locator('.recording').first()).toContainText('保存中');
};
const closeSaved = () => page.getByRole('button', { name: '关闭保存记录' }).click();
let ok = false;
try {
  const original = await readFile(source, 'utf8');
  await page.goto(url);
  await expect(page.locator('.log-row').last()).toContainText('temperature=1200');
  expect(await page.locator('.log-row').count()).toBeLessThan(75);
  await expect(page.locator('h1')).toHaveText('source');
  const logo = page.getByRole('img', { name: 'log_print LP logo', exact: true });
  await expect(logo).toHaveAttribute('src', '/log-print-mark.svg');
  await expect.poll(() => logo.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  await expect(page.getByRole('link', { name: /工作台/ })).toHaveCount(0);
  expect((await page.evaluate(() => performance.getEntriesByType('resource').map(r => r.name))).some(name => /canvas|charts|tables|components-|workbench/.test(name))).toBe(false);
  await screenshot('desktop-live-1440.png');
  // The former alternate URL can no longer load a second frontend.
  await page.goto(url + '?workbench');
  await expect(page.locator('.log-row').last()).toContainText('temperature=1200');
  await expect(page.locator('.vue-flow')).toHaveCount(0);
  checks.push('one application; former alternate URL has no legacy renderer or heavy bundles');

  await page.keyboard.press('ControlOrMeta+f');
  await expect(text).toBeFocused();
  await text.fill('temperature=12');
  await page.getByLabel('仅显示匹配', { exact: true }).check();
  await expect(page.locator('.log-row')).toHaveCount(12);
  await text.press('Enter');
  await expect(page.locator('.log-row.is-selected')).toContainText('temperature=12');
  await page.getByRole('button', { name: '日志详情', exact: true }).click();
  await page.getByRole('button', { name: '读取前后 8 行' }).click();
  await expect(page.locator('.context-lines')).toContainText('temperature=11');
  await expect(page.locator('.context-lines')).toContainText('temperature=13');
  await page.locator('.record-inspector').getByRole('button', { name: '复制', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('temperature=12');
  await expect.poll(async () => page.locator('.log-row.is-selected mark').evaluate(el => { const box = el.getBoundingClientRect(); const view = el.closest('.log-viewport').getBoundingClientRect(); return box.right <= view.right && box.left >= view.left; })).toBe(true);
  await screenshot('desktop-context-1440.png');
  await page.getByRole('button', { name: '关闭详情' }).click();
  await page.getByRole('grid', { name: '日志列表' }).focus();
  await page.keyboard.press('ArrowDown');
  await expect(page.locator('.log-row.is-selected')).toContainText('temperature=120');
  checks.push('keyboard search, literal filtering, grid navigation, original context and real clipboard');
  await page.getByRole('button', { name: '清除关键词' }).click();
  await page.getByLabel('仅显示匹配', { exact: true }).uncheck();
  await page.getByLabel('跟随最新', { exact: true }).check();
  await page.getByRole('button', { name: '暂停显示', exact: true }).click();
  await appendFile(source, 'pause-fixture\n');
  const stream = (await read()).streams.find(s => s.alias === 'source').id;
  await expect.poll(async () => (await api('logs.tail', { stream })).rows.some(r => r.text === 'pause-fixture')).toBe(true);
  await expect(page.locator('.log-row').last()).not.toContainText('pause-fixture');
  await saveFrom('从现在开始保存');
  await appendFile(source, 'saved-while-paused 中文\n');
  await expect.poll(async () => (await read()).recordings.some(r => Number(r.bytes) > 0)).toBe(true);
  await page.getByRole('button', { name: '停止并保存', exact: true }).click();
  await expect(page.locator('.recording')).toContainText('已保存');
  let download = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载 .log' }).click();
  expect(await readFile(await (await download).path(), 'utf8')).toBe('saved-while-paused 中文\n');
  await closeSaved();
  await page.getByRole('button', { name: '继续显示', exact: true }).click();
  await expect(page.locator('.log-row').last()).toContainText('saved-while-paused');
  await saveFrom('从最早可用数据保存');
  await page.getByRole('button', { name: '停止并保存', exact: true }).click();
  await expect(page.locator('.recording').first()).toContainText('已保存');
  download = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载 .log' }).first().click();
  expect(await readFile(await (await download).path(), 'utf8')).toBe(original + 'pause-fixture\nsaved-while-paused 中文\n');
  await screenshot('desktop-recordings.png');
  await closeSaved();
  checks.push('pause keeps collection and saving active; both save boundaries verified byte for byte');

  const fixture = 'FIRST 中文\n<script>window.injected=true</script>\nLAST without newline';
  await page.locator('input[type=file]').setInputFiles({ name: '中文-fixture.log', mimeType: 'text/plain', buffer: Buffer.from(fixture) });
  await expect(page.locator('h1')).toHaveText('中文-fixture.log');
  await expect(page.locator('.log-row')).toHaveCount(3);
  await expect(page.locator('.log-row').nth(1)).toContainText('<script>window.injected=true</script>');
  expect(await page.evaluate(() => window.injected)).toBeUndefined();
  await page.reload();
  await expect(page.locator('.log-row')).toHaveCount(3);
  const historyRequests = [];
  page.on('request', request => { if (request.url().endsWith('/api/control') && request.postDataJSON()?.method === 'history.read') historyRequests.push(request.postDataJSON()); });
  await text.fill('中文');
  await expect(page.locator('mark')).toHaveText('中文');
  await page.waitForTimeout(300); // Assert absence of a debounced scan on highlight-only edits.
  expect(historyRequests).toHaveLength(0);
  checks.push('import, UTF-8, hostile markup, unterminated line, refresh restoration; highlight does not rescan');

  await page.locator('.source-item').filter({ hasText: 'source' }).click();
  await page.getByRole('button', { name: '清除关键词' }).click();
  await page.setViewportSize({ width: 1280, height: 800 });
  await expect(page.locator('.log-row').last()).toContainText('saved-while-paused');
  await screenshot('desktop-live-1280.png');
  await page.getByRole('button', { name: '切换深色模式' }).click();
  await expect(page.locator('.log-app')).toHaveAttribute('data-theme', 'dark');
  await expect(page.locator('.source-item.selected')).toHaveCSS('background-color', 'rgb(32, 60, 52)');
  await screenshot('desktop-dark-1280.png');
  await page.reload();
  await expect(page.locator('.log-app')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: '切换浅色模式' }).click();

  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('.source-sidebar')).not.toBeVisible();
  await page.getByRole('button', { name: '打开来源' }).click();
  await expect(page.getByRole('dialog', { name: '来源', exact: true })).toBeVisible();
  await screenshot('mobile-sources-390.png');
  await page.locator('.source-item').filter({ hasText: '中文-fixture.log' }).click();
  await expect(page.locator('.source-sidebar')).not.toBeVisible();
  await expect(page.locator('.log-row')).toHaveCount(3);
  await expect(logo).toBeVisible();
  await screenshot('mobile-log-390.png');
  await page.locator('.log-row').first().click();
  await page.getByRole('button', { name: '日志详情', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '日志详情', exact: true })).toBeVisible();
  await page.keyboard.press('Tab');
  expect(await page.evaluate(() => !!document.activeElement.closest('.record-inspector'))).toBe(true);
  await screenshot('mobile-detail-390.png');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: '日志详情', exact: true })).toBeFocused();
  await page.getByRole('button', { name: '保存记录', exact: true }).click();
  await screenshot('mobile-recordings-390.png');
  await page.keyboard.press('Escape');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  checks.push('1440 and 1280 desktop, dark theme restore, 390 mobile drawers, focus return, no page overflow');

  await page.goto(emptyUrl);
  await expect(page.getByRole('heading', { name: '从一份日志开始' })).toBeVisible();
  await screenshot('mobile-empty-390.png');
  await page.setViewportSize({ width: 1440, height: 900 });
  await screenshot('desktop-empty-1440.png');
  await page.goto(url);
  await expect(page.locator('h1')).toHaveText('中文-fixture.log');
  await page.route('**/api/control', async route => {
    if (route.request().postDataJSON()?.method === 'history.read') await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '测试故障：历史暂时不可读' }) });
    else await route.continue();
  });
  await page.getByRole('button', { name: '历史', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('测试故障');
  await screenshot('desktop-error-1440.png');
  await page.unroute('**/api/control');
  await page.getByRole('button', { name: '关闭错误' }).click();
  await page.getByRole('button', { name: '历史', exact: true }).click();
  await expect(page.locator('.log-row')).toHaveCount(3);
  checks.push('empty state, explicit query failure, retry recovery');
  expect(errors).toEqual([]);
  ok = true;
} finally {
  if (!ok) await screenshot('failure.png').catch(() => {});
  await writeFile(path.join(artifact, 'browser.json'), JSON.stringify({ ok, errors, checks, platform: process.platform }, null, 2));
  await context.tracing.stop({ path: path.join(artifact, 'trace.zip') });
  await browser.close();
}
console.log(JSON.stringify({ ok, checks, artifact }, null, 2));
